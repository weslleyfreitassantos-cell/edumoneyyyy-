const choice = (prompt, options, answer, explanation, audioText = null) => ({
  type: 'MULTIPLE_CHOICE',
  instruction: audioText ? 'Ouça e escolha a resposta.' : 'Escolha a resposta adequada.',
  prompt,
  options,
  accepted: [answer],
  explanation,
  audioText,
});

const fill = (prompt, options, answer, explanation) => ({
  type: 'FILL_BLANK',
  instruction: 'Escolha a palavra que completa a expressão.',
  prompt,
  options,
  accepted: [answer],
  explanation,
});

const match = (prompt, pairs, explanation) => ({
  type: 'MATCHING',
  instruction: 'Associe cada expressão ao significado correto.',
  prompt,
  pairs,
  explanation,
});

const order = (prompt, answer, explanation) => ({
  type: 'WORD_ORDER',
  instruction: 'Monte a expressão usando as palavras disponíveis.',
  prompt,
  answer,
  explanation,
});

