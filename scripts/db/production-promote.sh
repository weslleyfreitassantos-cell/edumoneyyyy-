#!/usr/bin/env bash
set -euo pipefail
set +x

repo_root="$(git rev-parse --show-toplevel 2>/dev/null)" || {
  printf 'PROMOTION_ABORTED=repository_checkout_required\n' >&2
  exit 1
}
: "${TARGET_VERSION:?TARGET_VERSION is required}"
: "${EXPECTED_REMOTE_LAST:?EXPECTED_REMOTE_LAST is required}"
: "${EXPECTED_SOURCE_COMMIT:?EXPECTED_SOURCE_COMMIT is required}"
: "${EXPECTED_TARGET_SHA256:?EXPECTED_TARGET_SHA256 is required}"
unset TECESCOLA_VERIFIED_DATABASE_IDENTITY
unset BACKUP_GATE BACKUP_EXCEPTION_PR BACKUP_EXCEPTION_RELEASE_SHA
unset BACKUP_EXCEPTION_WINDOWS_PATH BACKUP_EXCEPTION_BACKUP_SHA256
unset BACKUP_EXCEPTION_BACKUP_FILE BACKUP_EXCEPTION_RESTORE_STATUS
unset BACKUP_EXCEPTION_STORAGE_STATUS BACKUP_EXCEPTION_OFFSITE_GATE
unset BACKUP_EXCEPTION_OFFSITE_STATUS BACKUP_EXCEPTION_RESTORE_RECEIPT_FILE
unset BACKUP_EXCEPTION_STORAGE_RECEIPT_FILE BACKUP_EXCEPTION_SOURCE_SHA
unset BACKUP_EXCEPTION_AUTHORIZATION ACCEPT_NO_BACKUP_COPY ACCEPT_NO_OFFSITE_COPY
unset ACCEPT_INCOMPLETE_RECOVERY_RISK
while IFS= read -r backup_variable; do
  unset "$backup_variable"
done < <(compgen -A variable BACKUP_)
unset REMOTE_LEDGER_FILE DRY_RUN_OUTPUT_FILE
unset PROMOTION_TEST_DB_URL PROMOTION_TEST_DB_CONTAINER PROMOTION_TEST_DATABASE_NAME
unset PROMOTION_TEST_CLI_LOG_DIR PROMOTION_TEST_SUPABASE_BIN PROMOTE_SINGLE_MIGRATION_CLI_BINARY
unset MOCK_APPLY_FAILURE MOCK_CLI_FAILURE MOCK_PSQL_FAILURE MOCK_AFTER_LEDGER_FILE
unset MOCK_AFTER_LEDGER_CONTENT MOCK_CLI_APPLY_COUNT_FILE MOCK_PSQL_CALL_COUNT_FILE
unset TECESCOLA_EXPECTED_DATABASE_IDENTITY PROMOTION_TEST_MODE
bash "$repo_root/scripts/db/production-connection.sh" run -- \
  bash "$repo_root/scripts/db/promote-single-migration.sh"
