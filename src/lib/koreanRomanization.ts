const KOREAN_ROMANIZATION_PATTERN = new RegExp(
  Object.keys(KOREAN_ROMANIZATION)
    .sort((left, right) => right.length - left.length)
    .map((text) => text.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&'))
    .join('|'),
  'gu',
);

export interface KoreanRomanizationPart {
  text: string;
  romanization?: string;
}

export function koreanRomanizationParts(text: string): KoreanRomanizationPart[] {
  const parts: KoreanRomanizationPart[] = [];
  let cursor = 0;

  for (const match of text.matchAll(KOREAN_ROMANIZATION_PATTERN)) {
    const matchedText = match[0];
    const start = match.index ?? 0;
    const romanization = KOREAN_ROMANIZATION[matchedText];
    if (!romanization) continue;

    if (start > cursor) parts.push({ text: text.slice(cursor, start) });
    const existingReading = text.slice(start + matchedText.length).match(/^\s*\(([^)]+)\)/u)?.[1];
    const alreadyHasReading = existingReading?.replace(/\s+/gu, '').toLocaleLowerCase()
      === romanization.replace(/\s+/gu, '').toLocaleLowerCase();
    parts.push({ text: matchedText, romanization: alreadyHasReading ? undefined : romanization });
    cursor = start + matchedText.length;
  }

  if (cursor < text.length) parts.push({ text: text.slice(cursor) });
  return parts.length ? parts : [{ text }];
}

export function koreanRomanizedText(text: string): string {
  return koreanRomanizationParts(text)
    .map(({ text: part, romanization }) => romanization ? `${part} (${romanization})` : part)
    .join('');
}
